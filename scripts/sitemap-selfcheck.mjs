/**
 * Mutation-test sitemap-check.mjs by reintroducing the exact defect it exists to
 * catch: an XML comment whose body contains `--`.
 *
 * `node scripts/sitemap-selfcheck.mjs`
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const FILE = 'public/sitemap.xml';
const CHECK = 'scripts/sitemap-check.mjs';
const original = readFileSync(FILE, 'utf8');

const MUTATIONS = [
  [
    'a comment containing `--` (what shipped, and what Search Console rejected)',
    (s) =>
      s.replace(
        '<urlset',
        '<!-- why there is no fragment -- the answer is not obvious -->\n<urlset'
      )
  ],
  [
    'a harmless comment with no `--` in it (still forbidden here: prose must live elsewhere)',
    (s) => s.replace('<urlset', '<!-- generated by hand -->\n<urlset')
  ],
  [
    'a comment containing a fragment, which also trips the no-fragment rule',
    (s) => s.replace('<urlset', '<!-- /#about is not listed here -->\n<urlset')
  ],
  ['a fragment in a URL', (s) => s.replace('<loc>https://thepulse.us.ci/about</loc>', '<loc>https://thepulse.us.ci/#about</loc>')],
  ['a canonical pointing at a different domain', (s) => s.replace('thepulse.us.ci/credits', 'thewire.us.ci/credits')],
  ['an unbalanced element', (s) => s.replace('</urlset>', '')],
  ['a URL with no rewrite behind it', (s) => s.replace('<loc>https://thepulse.us.ci/assignments</loc>', '<loc>https://thepulse.us.ci/nope</loc>')]
];

let survived = 0;

for (const [label, mutate] of MUTATIONS) {
  const mutated = mutate(original);
  if (mutated === original) {
    console.log(`  SKIP    ${label} -- anchor not found`);
    survived += 1;
    continue;
  }
  writeFileSync(FILE, mutated);
  let caught = false;
  try {
    execFileSync('node', [CHECK], { stdio: 'pipe' });
  } catch {
    caught = true;
  }
  console.log(`  ${caught ? 'CAUGHT ' : 'MISSED '} ${label}`);
  if (!caught) survived += 1;
}

writeFileSync(FILE, original);
const restored = readFileSync(FILE, 'utf8');
console.log('\nrestored:', restored === original ? 'verified byte-for-byte' : 'RESTORE FAILED');
process.exit(survived ? 1 : 0);